"""
Intelligent Decision-Support Alert Engine

Generates transparent, threshold-based alerts for human verification when
compound risk conditions are satisfied. Alerts are decision-support
notifications and MUST NOT be treated as confirmed warnings.
"""

import json
import sys
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, List, Optional

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from config.settings import RISK, CREDENTIALS, setup_logging
from src.data.db import get_db

logger = setup_logging("alert_engine")

DISCLAIMER = (
    "This is a decision-support notification generated by an automated monitoring system. "
    "It does NOT constitute a confirmed landslide warning. All alerts require verification "
    "by relevant authorities and field inspection before any action is taken."
)


# -----------------------------------------------------------------------------
# 4-TIER WARNING LEVEL HIERARCHY
# -----------------------------------------------------------------------------
# Scientifically grounded criteria for Tirumala Hills:
#   1. Normal: Baseline monitoring conditions; indicators within seasonal variance.
#   2. Watch: Early advisory; rainfall accumulation 50-75mm or moderate slope concern.
#   3. Elevated concern: Rainfall 75-100mm, or localized InSAR LOS movement (10-15mm).
#   4. High concern: Multi-criteria compound hazard: rainfall >100mm on steep terrain (>25°),
#                    or significant InSAR displacement (>15mm) with high coherence (γ≥0.65).
class WarningLevel:
    NORMAL = "Normal"
    WATCH = "Watch"
    ELEVATED = "Elevated concern"
    HIGH = "High concern"


@dataclass
class AlertPayload:
    """Structured alert for human review."""
    alert_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    timestamp: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    trigger_rule: str = ""
    severity: str = "INFO"  # INFO, WARNING, CRITICAL
    warning_level: str = WarningLevel.WATCH  # Normal, Watch, Elevated concern, High concern
    affected_cells: List[str] = field(default_factory=list)
    affected_cells_count: int = 0
    center_lat: float = 0.0
    center_lon: float = 0.0
    max_risk_score: float = 0.0
    indicators: Dict = field(default_factory=dict)
    observation_date: str = ""
    data_quality: str = "GOOD"
    summary: str = ""
    recommended_action: str = ""
    disclaimer: str = DISCLAIMER


class AlertRulesEngine:
    """Evaluates multi-criteria alert rules against observation data."""

    def __init__(self):
        self.db = get_db()

    def evaluate_all_rules(
        self, evidence_df: pd.DataFrame,
        rainfall_3day_mm: Optional[float] = 0.0,
        observation_date: str = "",
    ) -> List[AlertPayload]:
        """Run all alert rules and return triggered alerts."""
        if evidence_df is None or evidence_df.empty:
            return []

        df = evidence_df.copy()
        if "risk_score" not in df.columns:
            from src.risk_assessment import build_spatial_risk
            scored_df, _ = build_spatial_risk(df)
            if not scored_df.empty and "risk_score" in scored_df.columns:
                df = scored_df

        alerts = []

        a1 = self._rule_1_rainfall_slope(df, rainfall_3day_mm, observation_date)
        if a1:
            alerts.append(a1)

        a2 = self._rule_2_insar_near_gsi(df, observation_date)
        if a2:
            alerts.append(a2)

        a3 = self._rule_3_high_risk_cluster(df, observation_date)
        if a3:
            alerts.append(a3)

        a4 = self._rule_4_category_escalation(df, observation_date)
        if a4:
            alerts.append(a4)

        logger.info("Alert evaluation: %d rules triggered out of 4.", len(alerts))
        return alerts

    def _rule_1_rainfall_slope(
        self, df: pd.DataFrame, rainfall_3day_mm: Optional[float], obs_date: str
    ) -> Optional[AlertPayload]:
        """
        Rule 1: 3-day rainfall > threshold AND localized high slope.
        
        Condition: rainfall_3day > 100 mm AND slope > 25°
        """
        if (
            rainfall_3day_mm is None
            or rainfall_3day_mm < RISK.alert_rainfall_3day_mm
        ):
            return None

        high_slope = df[df.get("slope_deg", pd.Series(dtype=float)) >= RISK.high_slope_deg]
        if high_slope.empty:
            return None

        lat_col = "latitude" if "latitude" in high_slope.columns else None
        lon_col = "longitude" if "longitude" in high_slope.columns else None

        return AlertPayload(
            trigger_rule="RULE_1_RAINFALL_SLOPE",
            severity="CRITICAL",
            warning_level=WarningLevel.HIGH,
            affected_cells=high_slope.get("cell_id", pd.Series()).tolist()[:50],
            affected_cells_count=len(high_slope),
            center_lat=float(high_slope[lat_col].mean()) if lat_col else 13.668,
            center_lon=float(high_slope[lon_col].mean()) if lon_col else 79.374,
            max_risk_score=float(high_slope.get("risk_score", pd.Series([0])).max()),
            indicators={
                "rainfall_3day_mm": rainfall_3day_mm,
                "high_slope_cells": len(high_slope),
                "threshold_rainfall_mm": RISK.alert_rainfall_3day_mm,
                "threshold_slope_deg": RISK.high_slope_deg,
            },
            observation_date=obs_date,
            summary=f"Elevated rainfall ({rainfall_3day_mm:.0f} mm in 3 days) combined with "
                    f"{len(high_slope)} steep-slope cells (≥{RISK.high_slope_deg}°).",
            recommended_action="Review rainfall trend. If sustained, consider field inspection "
                              "of steep slope areas along Ghat roads.",
        )

    def _rule_2_insar_near_gsi(
        self, df: pd.DataFrame, obs_date: str
    ) -> Optional[AlertPayload]:
        """
        Rule 2: Significant LOS displacement near GSI historical points.
        
        Condition: |LOS| > 15mm with γ ≥ 0.65 within 500m of GSI points
        """
        if "los_disp_m" not in df.columns or "dist_to_gsi_km" not in df.columns:
            return None

        # Find cells with significant displacement near GSI points
        significant = df[
            (df["los_disp_m"].abs() * 1000 >= RISK.alert_los_mm) &
            (df.get("correlation", df.get("coherence", pd.Series(dtype=float))) >= RISK.high_coherence) &
            (df["dist_to_gsi_km"] <= RISK.alert_gsi_proximity_km)
        ]

        if significant.empty:
            return None

        lat_col = "latitude" if "latitude" in significant.columns else None
        lon_col = "longitude" if "longitude" in significant.columns else None

        return AlertPayload(
            trigger_rule="RULE_2_INSAR_GSI_PROXIMITY",
            severity="WARNING",
            warning_level=WarningLevel.ELEVATED,
            affected_cells=significant.get("cell_id", pd.Series()).tolist()[:50],
            affected_cells_count=len(significant),
            center_lat=float(significant[lat_col].mean()) if lat_col else 13.668,
            center_lon=float(significant[lon_col].mean()) if lon_col else 79.374,
            max_risk_score=float(significant.get("risk_score", pd.Series([0])).max()),
            indicators={
                "max_los_mm": float(significant["los_disp_m"].abs().max() * 1000),
                "mean_coherence": float(significant.get("correlation",
                    significant.get("coherence", pd.Series([0]))).mean()),
                "near_gsi_cells": len(significant),
            },
            observation_date=obs_date,
            summary=f"{len(significant)} cells show significant LOS displacement "
                    f"(>{RISK.alert_los_mm}mm) near historical landslide locations.",
            recommended_action="Investigate InSAR displacement pattern. Cross-check with "
                              "field observations. Note: atmospheric effects may cause false signals.",
        )

    def _rule_3_high_risk_cluster(
        self, df: pd.DataFrame, obs_date: str
    ) -> Optional[AlertPayload]:
        """
        Rule 3: Cluster of high-risk cells.
        
        Condition: Risk score ≥ 66.67 across ≥ 3 contiguous cells
        """
        risk_col = None
        for col in ["risk_score", "agent_evidence_score"]:
            if col in df.columns:
                risk_col = col
                break

        if risk_col is None:
            return None

        high_risk = df[df[risk_col] >= RISK.alert_risk_score]
        if len(high_risk) < RISK.alert_cluster_min_cells:
            return None

        lat_col = "latitude" if "latitude" in high_risk.columns else None
        lon_col = "longitude" if "longitude" in high_risk.columns else None

        return AlertPayload(
            trigger_rule="RULE_3_HIGH_RISK_CLUSTER",
            severity="CRITICAL" if len(high_risk) >= 10 else "WARNING",
            warning_level=WarningLevel.HIGH if len(high_risk) >= 10 else WarningLevel.ELEVATED,
            affected_cells=high_risk.get("cell_id", pd.Series()).tolist()[:50],
            affected_cells_count=len(high_risk),
            center_lat=float(high_risk[lat_col].mean()) if lat_col else 13.668,
            center_lon=float(high_risk[lon_col].mean()) if lon_col else 79.374,
            max_risk_score=float(high_risk[risk_col].max()),
            indicators={
                "high_risk_cells": len(high_risk),
                "max_score": float(high_risk[risk_col].max()),
                "mean_score": float(high_risk[risk_col].mean()),
            },
            observation_date=obs_date,
            summary=f"{len(high_risk)} cells exhibit high compound risk scores "
                    f"(≥{RISK.alert_risk_score:.0f}).",
            recommended_action="Review multi-criteria evidence for affected cells. "
                              "Prioritize areas near infrastructure for field verification.",
        )

    def _rule_4_category_escalation(
        self, df: pd.DataFrame, obs_date: str
    ) -> Optional[AlertPayload]:
        """
        Rule 4: Risk category escalation from previous observation.
        """
        risk_cat_col = None
        for col in ["risk_category", "agent_evidence_category"]:
            if col in df.columns:
                risk_cat_col = col
                break

        if risk_cat_col is None:
            return None

        # Check database for previous observation
        try:
            dates = self.db.get_observation_dates()
            if len(dates) < 2:
                return None
        except Exception:
            return None

        high_cells = df[df[risk_cat_col] == "High"]
        if len(high_cells) < 5:
            return None

        return AlertPayload(
            trigger_rule="RULE_4_CATEGORY_ESCALATION",
            severity="INFO",
            warning_level=WarningLevel.WATCH,
            affected_cells_count=len(high_cells),
            center_lat=13.668, center_lon=79.374,
            max_risk_score=float(df.get("risk_score", df.get("agent_evidence_score", pd.Series([0]))).max()),
            observation_date=obs_date,
            summary=f"{len(high_cells)} cells classified as High risk in current assessment.",
            recommended_action="Compare with previous observation to identify newly escalated areas.",
        )


def export_alerts_geojson(alerts: List[AlertPayload], output_path: Optional[str] = None) -> str:
    """Export active decision-support alerts as GeoJSON for 3D Cesium visualization."""
    from config.settings import PATHS
    out_file = Path(output_path or (PATHS.viewer_data / "active_alerts.geojson"))
    out_file.parent.mkdir(parents=True, exist_ok=True)

    features = []
    for al in alerts:
        features.append({
            "type": "Feature",
            "geometry": {
                "type": "Point",
                "coordinates": [al.center_lon, al.center_lat],
            },
            "properties": {
                "alert_id": al.alert_id,
                "timestamp": al.timestamp,
                "trigger_rule": al.trigger_rule,
                "severity": al.severity,
                "warning_level": al.warning_level,
                "affected_cells_count": al.affected_cells_count,
                "max_risk_score": round(al.max_risk_score, 1),
                "summary": al.summary,
                "recommended_action": al.recommended_action,
            }
        })

    fc = {
        "type": "FeatureCollection",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "total_alerts": len(features),
        "features": features,
    }
    with open(out_file, "w") as f:
        json.dump(fc, f, indent=2)
    logger.info("Exported %d active alerts to GeoJSON: %s", len(features), out_file)
    return str(out_file)


def save_alerts_to_db(alerts: List[AlertPayload]):
    """Persist new alerts once per rule and observation, then export pending alerts."""
    db = get_db()
    inserted = []
    for alert in alerts:
        with db.cursor() as cur:
            duplicate = cur.execute(
                "SELECT 1 FROM alerts WHERE trigger_rule = ? AND observation_date = ? LIMIT 1",
                (alert.trigger_rule, alert.observation_date),
            ).fetchone()
        if duplicate:
            continue

        db.add_alert(
            alert_id=alert.alert_id,
            alert_timestamp=alert.timestamp,
            trigger_rule=alert.trigger_rule,
            severity=alert.severity,
            affected_cells=json.dumps(alert.affected_cells[:50]),
            affected_cells_count=alert.affected_cells_count,
            center_latitude=alert.center_lat,
            center_longitude=alert.center_lon,
            max_risk_score=alert.max_risk_score,
            triggering_indicators=json.dumps(alert.indicators),
            observation_date=alert.observation_date,
            data_quality=alert.data_quality,
            summary_text=alert.summary,
            recommended_action=alert.recommended_action,
        )
        inserted.append(alert)

        channels = []
        if CREDENTIALS.telegram_bot_token and CREDENTIALS.telegram_chat_id:
            if send_telegram_notification(alert):
                channels.append("telegram")
        if (
            CREDENTIALS.smtp_username
            and CREDENTIALS.smtp_password
            and CREDENTIALS.alert_email_to
        ):
            if send_email_notification(alert):
                channels.append("email")
        if channels:
            with db.cursor() as cur:
                cur.execute(
                    "UPDATE alerts SET notification_sent = 1, notification_channel = ? "
                    "WHERE alert_id = ?",
                    (",".join(channels), alert.alert_id),
                )

    active_alerts = []
    for record in db.get_active_alerts():
        try:
            affected_cells = json.loads(record.get("affected_cells") or "[]")
            indicators = json.loads(record.get("triggering_indicators") or "{}")
        except (TypeError, json.JSONDecodeError):
            affected_cells, indicators = [], {}
        active_alerts.append(AlertPayload(
            alert_id=record["alert_id"],
            timestamp=record.get("alert_timestamp", ""),
            trigger_rule=record.get("trigger_rule", ""),
            severity=record.get("severity", "INFO"),
            warning_level=(
                WarningLevel.HIGH if record.get("severity") == "CRITICAL"
                else WarningLevel.ELEVATED if record.get("severity") == "WARNING"
                else WarningLevel.WATCH
            ),
            affected_cells=affected_cells,
            affected_cells_count=record.get("affected_cells_count", 0),
            center_lat=record.get("center_latitude", 0.0),
            center_lon=record.get("center_longitude", 0.0),
            max_risk_score=record.get("max_risk_score", 0.0),
            indicators=indicators,
            observation_date=record.get("observation_date", ""),
            data_quality=record.get("data_quality", "GOOD"),
            summary=record.get("summary_text", ""),
            recommended_action=record.get("recommended_action", ""),
        ))

    logger.info("Saved %d new alerts; %d alerts remain pending review.", len(inserted), len(active_alerts))
    export_alerts_geojson(active_alerts)
    return len(inserted)


def send_telegram_notification(alert: AlertPayload) -> bool:
    """Send alert via Telegram bot (optional)."""
    if not CREDENTIALS.telegram_bot_token or not CREDENTIALS.telegram_chat_id:
        return False

    try:
        import requests
        msg = (
            f"🏔️ Tirumala Landslide Monitor Alert\n"
            f"━━━━━━━━━━━━━━━━━━━━━━━━\n"
            f"Rule: {alert.trigger_rule}\n"
            f"Severity: {alert.severity}\n"
            f"Date: {alert.observation_date}\n"
            f"Cells: {alert.affected_cells_count}\n"
            f"Max Score: {alert.max_risk_score:.1f}\n\n"
            f"{alert.summary}\n\n"
            f"⚠️ {DISCLAIMER[:100]}..."
        )
        url = f"https://api.telegram.org/bot{CREDENTIALS.telegram_bot_token}/sendMessage"
        resp = requests.post(url, json={
            "chat_id": CREDENTIALS.telegram_chat_id,
            "text": msg, "parse_mode": "HTML",
        }, timeout=10)
        resp.raise_for_status()
        payload = resp.json()
        if not payload.get("ok"):
            logger.warning("Telegram API rejected alert %s: %s", alert.alert_id, payload)
            return False
        logger.info("Telegram notification delivered for alert %s.", alert.alert_id)
        return True
    except Exception as e:
        logger.warning("Telegram notification failed (%s).", type(e).__name__)
        return False


def send_email_notification(alert: AlertPayload) -> bool:
    """Send alert via email (optional)."""
    if (
        not CREDENTIALS.smtp_username
        or not CREDENTIALS.smtp_password
        or not CREDENTIALS.alert_email_to
    ):
        return False

    try:
        import smtplib
        from email.mime.text import MIMEText

        msg = MIMEText(
            f"Alert Rule: {alert.trigger_rule}\n"
            f"Severity: {alert.severity}\n"
            f"Date: {alert.observation_date}\n"
            f"Affected Cells: {alert.affected_cells_count}\n"
            f"Max Risk Score: {alert.max_risk_score:.1f}\n\n"
            f"{alert.summary}\n\n"
            f"Recommended Action: {alert.recommended_action}\n\n"
            f"{DISCLAIMER}",
        )
        msg["Subject"] = f"[Tirumala Monitor] {alert.severity}: {alert.trigger_rule}"
        msg["From"] = CREDENTIALS.smtp_username
        msg["To"] = CREDENTIALS.alert_email_to

        with smtplib.SMTP(CREDENTIALS.smtp_host, CREDENTIALS.smtp_port) as server:
            server.starttls()
            server.login(CREDENTIALS.smtp_username, CREDENTIALS.smtp_password)
            server.send_message(msg)
        logger.info("Email notification delivered for alert %s.", alert.alert_id)
        return True
    except Exception as e:
        logger.warning("Email notification failed (%s).", type(e).__name__)
        return False
