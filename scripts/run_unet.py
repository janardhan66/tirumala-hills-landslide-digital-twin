"""
Batch U-Net Inference on Tirumala Hills

Loads the existing Landslide4Sense 14-channel U-Net checkpoint, runs inference
on patches generated by tirumala_patch_builder, and stitches predictions into
a georeferenced mosaic.

DISCLAIMER: The U-Net model was trained on the Landslide4Sense benchmark dataset.
It has NOT been fine-tuned or validated on Tirumala Hills imagery.
Predictions must be treated as exploratory indicators and should NOT be
interpreted as confirmed landslide detections without field verification.
"""

import argparse
import json
import sys
import time
from datetime import datetime
from pathlib import Path
from typing import Dict, Optional

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from config.settings import PATHS, UNET, STUDY_AREA, setup_logging

logger = setup_logging("run_unet")


def load_unet_model(checkpoint_path: Optional[str] = None):
    """Load the 14-channel U-Net model from checkpoint."""
    ckpt_path = checkpoint_path or str(PATHS.unet_checkpoint)
    if not Path(ckpt_path).exists():
        logger.error("Checkpoint not found: %s", ckpt_path)
        return None

    try:
        import torch
        sys.path.insert(0, str(PATHS.root))
        from src.models.landslide_segmentation import UNet
        model = UNet(in_channels=UNET.input_channels, out_channels=UNET.output_channels)
    except Exception as e:
        logger.warning("Could not import UNet from landslide_segmentation: %s. Using exact replica.", e)
        import torch
        import torch.nn as nn

        class DoubleConv(nn.Module):
            def __init__(self, in_channels, out_channels):
                super().__init__()
                self.block = nn.Sequential(
                    nn.Conv2d(in_channels, out_channels, kernel_size=3, padding=1),
                    nn.BatchNorm2d(out_channels),
                    nn.ReLU(inplace=True),
                    nn.Conv2d(out_channels, out_channels, kernel_size=3, padding=1),
                    nn.BatchNorm2d(out_channels),
                    nn.ReLU(inplace=True)
                )

            def forward(self, x):
                return self.block(x)

        class UNet(nn.Module):
            def __init__(self, in_channels=14, out_channels=1):
                super().__init__()
                self.enc1 = DoubleConv(in_channels, 32)
                self.enc2 = DoubleConv(32, 64)
                self.enc3 = DoubleConv(64, 128)
                self.pool = nn.MaxPool2d(2, 2)
                self.bottleneck = DoubleConv(128, 256)
                self.up3 = nn.ConvTranspose2d(256, 128, 2, 2)
                self.dec3 = DoubleConv(256, 128)
                self.up2 = nn.ConvTranspose2d(128, 64, 2, 2)
                self.dec2 = DoubleConv(128, 64)
                self.up1 = nn.ConvTranspose2d(64, 32, 2, 2)
                self.dec1 = DoubleConv(64, 32)
                self.output = nn.Conv2d(32, out_channels, 1)

            def forward(self, x):
                e1 = self.enc1(x)
                e2 = self.enc2(self.pool(e1))
                e3 = self.enc3(self.pool(e2))
                b = self.bottleneck(self.pool(e3))
                d3 = self.up3(b)
                d3 = torch.cat([d3, e3], dim=1)
                d3 = self.dec3(d3)
                d2 = self.up2(d3)
                d2 = torch.cat([d2, e2], dim=1)
                d2 = self.dec2(d2)
                d1 = self.up1(d2)
                d1 = torch.cat([d1, e1], dim=1)
                d1 = self.dec1(d1)
                return self.output(d1)

        model = UNet(in_channels=UNET.input_channels, out_channels=UNET.output_channels)

    try:
        state = torch.load(ckpt_path, map_location="cpu", weights_only=True)
        if isinstance(state, dict) and "model_state_dict" in state:
            model.load_state_dict(state["model_state_dict"])
        else:
            model.load_state_dict(state)
        model.eval()
        logger.info("U-Net checkpoint loaded: %s", Path(ckpt_path).name)
        return model
    except Exception as e:
        logger.error("Failed to load checkpoint: %s", e)
        return None


def run_inference(
    model,
    patches: list,
    threshold: float = 0.50,
    batch_size: int = 2,
) -> list:
    """
    Run U-Net inference on a list of patches.
    
    Returns list of dicts with 'prediction' (binary mask) and 'confidence' arrays.
    """
    if model is None:
        raise ValueError("A loaded U-Net model is required for inference.")
    if not patches:
        raise ValueError("At least one valid input patch is required.")
    if not 0.0 <= threshold <= 1.0:
        raise ValueError("Inference threshold must be between 0 and 1.")
    if batch_size < 1:
        raise ValueError("Inference batch size must be a positive integer.")

    import torch

    results = []
    total = len(patches)

    for i in range(0, total, batch_size):
        batch_patches = patches[i : i + batch_size]
        tensors = [torch.from_numpy(p["tensor"]).unsqueeze(0) for p in batch_patches]
        batch_tensor = torch.cat(tensors, dim=0)

        with torch.no_grad():
            logits = model(batch_tensor)
            probs = torch.sigmoid(logits)

        for j, p in enumerate(batch_patches):
            prob_map = probs[j, 0].numpy()
            binary = (prob_map >= threshold).astype(np.uint8)
            results.append({
                "prediction": binary,
                "confidence": prob_map,
                "row_start": p["row_start"],
                "col_start": p["col_start"],
                "has_optical": p["has_optical"],
                "valid_fraction": p["valid_fraction"],
                "mean_confidence": float(np.mean(prob_map)),
                "positive_fraction": float(np.mean(binary)),
            })

        if (i + batch_size) % 10 == 0:
            logger.info("Inference progress: %d/%d patches.", min(i + batch_size, total), total)

    return results


def stitch_predictions(
    results: list,
    grid_shape: tuple,
    patch_size: int = 128,
) -> tuple:
    """
    Stitch overlapping patch predictions into a single mosaic.
    
    Uses averaging for overlapping regions.
    Returns (prediction_mosaic, confidence_mosaic, count_mosaic).
    """
    H, W = grid_shape
    if H <= 0 or W <= 0:
        raise ValueError("Prediction grid dimensions must be positive.")
    if not results:
        raise ValueError("Cannot stitch an empty prediction result.")
    # Pad to accommodate patches
    pad_H = max(H, max(r["row_start"] + patch_size for r in results))
    pad_W = max(W, max(r["col_start"] + patch_size for r in results))

    conf_sum = np.zeros((pad_H, pad_W), dtype=np.float64)
    count = np.zeros((pad_H, pad_W), dtype=np.float64)

    for r in results:
        rs = r["row_start"]
        cs = r["col_start"]
        conf_sum[rs : rs + patch_size, cs : cs + patch_size] += r["confidence"]
        count[rs : rs + patch_size, cs : cs + patch_size] += 1.0

    # Average
    count[count == 0] = 1.0
    confidence = (conf_sum / count)[:H, :W]
    prediction = (confidence >= 0.50).astype(np.uint8)

    return prediction, confidence.astype(np.float32), count[:H, :W]


def save_prediction_geotiff(
    prediction: np.ndarray,
    confidence: np.ndarray,
    reference_tif: str,
    output_dir: str,
    observation_date: str,
) -> dict:
    """Save prediction and confidence as georeferenced GeoTIFFs."""
    import rasterio

    if prediction.ndim != 2 or confidence.ndim != 2:
        raise ValueError("Prediction and confidence must be two-dimensional arrays.")
    if prediction.shape != confidence.shape:
        raise ValueError("Prediction and confidence rasters must have matching shapes.")
    if not np.all(np.isin(prediction, (0, 1))):
        raise ValueError("Prediction raster must contain only binary 0/1 values.")
    if not np.all(np.isfinite(confidence)) or np.any(
        (confidence < 0) | (confidence > 1)
    ):
        raise ValueError("Confidence values must be finite and between 0 and 1.")

    out_dir = Path(output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    with rasterio.open(reference_tif) as ref:
        if prediction.shape != ref.shape:
            raise ValueError(
                f"Prediction shape {prediction.shape} does not match reference "
                f"raster shape {ref.shape}."
            )
        valid_mask = ref.dataset_mask() > 0
        profile = ref.profile.copy()
        profile.update(dtype="uint8", count=1, compress="lzw", nodata=255)

        pred_path = out_dir / f"unet_prediction_{observation_date}.tif"
        pred_data = prediction.astype(np.uint8, copy=True)
        pred_data[~valid_mask] = 255
        with rasterio.open(pred_path, "w", **profile) as dst:
            dst.write(pred_data, 1)

        profile.update(dtype="float32", nodata=-9999)
        conf_path = out_dir / f"unet_confidence_{observation_date}.tif"
        conf_data = confidence.astype(np.float32, copy=True)
        conf_data[~valid_mask] = -9999
        with rasterio.open(conf_path, "w", **profile) as dst:
            dst.write(conf_data, 1)

    logger.info("Saved prediction: %s", pred_path)
    logger.info("Saved confidence: %s", conf_path)
    return {
        "prediction_tif": str(pred_path),
        "confidence_tif": str(conf_path),
    }


def main():
    parser = argparse.ArgumentParser(
        description="Run U-Net inference on Tirumala Hills patches."
    )
    parser.add_argument("--checkpoint", default=str(PATHS.unet_checkpoint))
    parser.add_argument("--threshold", type=float, default=UNET.threshold)
    parser.add_argument("--batch-size", type=int, default=UNET.batch_size)
    parser.add_argument("--stride", type=int, default=64)
    parser.add_argument("--s2-dir", default=None, help="Sentinel-2 bands directory.")
    parser.add_argument("--observation-date", default=datetime.now().astimezone().strftime("%Y-%m-%d"))
    parser.add_argument("--output-dir", default=str(PATHS.outputs_dir / "unet_predictions"))
    args = parser.parse_args()

    logger.info("=" * 60)
    logger.info("U-Net Inference Pipeline — Tirumala Hills")
    logger.info("DISCLAIMER: Predictions from Landslide4Sense benchmark model.")
    logger.info("NOT validated on Tirumala Hills imagery.")
    logger.info("=" * 60)

    # Step 1: Build patches
    from src.models.tirumala_patch_builder import TirumalaPatchBuilder

    builder = TirumalaPatchBuilder(stride=args.stride)
    if not builder.prepare(s2_dir=args.s2_dir):
        raise RuntimeError(
            "Patch preparation failed; aligned DEM, slope, and all 12 Sentinel-2 "
            "bands are required."
        )

    patches = builder.extract_patches()
    if not patches:
        raise RuntimeError("No valid Sentinel-2 input patches were generated.")

    # Step 2: Load model
    model = load_unet_model(args.checkpoint)
    if model is None:
        raise RuntimeError(f"Unable to load U-Net checkpoint: {args.checkpoint}")

    # Step 3: Run inference
    start_time = time.time()
    results = run_inference(model, patches, args.threshold, args.batch_size)
    duration = time.time() - start_time

    # Step 4: Stitch
    grid_shape = (STUDY_AREA.grid_rows, STUDY_AREA.grid_cols)
    prediction, confidence, counts = stitch_predictions(results, grid_shape)

    # Step 5: Save
    output_files = save_prediction_geotiff(
        prediction, confidence,
        str(PATHS.dem_tif), args.output_dir, args.observation_date,
    )

    # Step 6: Summary
    summary = {
        "observation_date": args.observation_date,
        "total_patches": len(patches),
        "inference_duration_seconds": round(duration, 1),
        "mean_confidence": round(float(np.mean(confidence)), 4),
        "positive_pixel_fraction": round(float(np.mean(prediction)), 4),
        "total_positive_pixels": int(np.sum(prediction)),
        "grid_shape": list(grid_shape),
        "threshold": args.threshold,
        "has_optical_data": any(p["has_optical"] for p in patches),
        "disclaimer": (
            "Predictions from Landslide4Sense benchmark U-Net. "
            "Not validated on Tirumala-specific imagery."
        ),
        **output_files,
    }

    # Save summary JSON
    summary_path = Path(args.output_dir) / f"unet_summary_{args.observation_date}.json"
    summary_path.parent.mkdir(parents=True, exist_ok=True)
    with open(summary_path, "w") as f:
        json.dump(summary, f, indent=2)

    logger.info("Inference complete: %s", json.dumps(summary, indent=2))
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
