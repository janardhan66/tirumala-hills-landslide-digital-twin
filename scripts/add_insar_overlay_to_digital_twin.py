
from pathlib import Path
import re

BASE_DIR = Path(__file__).resolve().parent.parent

HTML_FILE = (
    BASE_DIR
    / "results"
    / "digital_twin"
    / "tirumala_final_digital_twin.html"
)

OVERLAY_FILE = (
    BASE_DIR
    / "results"
    / "digital_twin"
    / "tirumala_insar_los_overlay.png"
)

# Geographic bounds: west, south, east, north.
WEST = 79.3292463736464
SOUTH = 13.63915149344645
EAST = 79.42062161334384
NORTH = 13.701210154056298

html = HTML_FILE.read_text(encoding="utf-8")

if not OVERLAY_FILE.exists():
    raise FileNotFoundError(f"Overlay PNG not found: {OVERLAY_FILE}")

# Use an embedded image so the overlay also works inside Streamlit.
import base64

image_data = base64.b64encode(OVERLAY_FILE.read_bytes()).decode("ascii")
image_url = f"data:image/png;base64,{image_data}"

if "TIRUMALA_INSAR_OVERLAY_ADDED" in html:
    raise RuntimeError(
        "The InSAR overlay appears to be installed already. "
        "Restore the backup before running this script again."
    )

# Find the existing map variable generated by Folium.
map_match = re.search(
    r"var (map_[A-Za-z0-9_]+) = L\.map\(",
    html,
)

if not map_match:
    raise RuntimeError("Could not find the Folium map variable in the HTML.")

map_variable = map_match.group(1)


# Add Esri World Topographic Map background.

map_init = re.search(
    rf"(var {re.escape(map_variable)} = L\.map\([\s\S]*?\);)",
    html,
)

if not map_init:
    raise RuntimeError("Could not find the Leaflet map initialization.")

tile_code = f"""
L.tileLayer(
    'https://server.arcgisonline.com/ArcGIS/rest/services/World_Topo_Map/MapServer/tile/{{z}}/{{y}}/{{x}}',
    {{
        maxZoom: 19,
        attribution: 'Tiles &copy; Esri'
    }}
).addTo({map_variable});
"""

html = html[:map_init.end()] + "\\n" + tile_code + html[map_init.end():]

# Add the raster overlay before the existing layer control is created.
# Insert the overlay before the layer-control overlays dictionary is created.
layer_control_marker = "var layer_control_"
control_index = html.find(layer_control_marker)

if control_index < 0:
    raise RuntimeError(
        "Could not find the existing Leaflet layer-control declaration."
    )

# Move to the beginning of the JavaScript declaration line.
control_index = html.rfind("\n", 0, control_index) + 1

overlay_code = f"""
// TIRUMALA_INSAR_OVERLAY_ADDED
var tirumalaInsarOverlay = L.imageOverlay(
    "{image_url}",
    [[{SOUTH}, {WEST}], [{NORTH}, {EAST}]],
    {{
        opacity: 0.78,
        interactive: false,
        alt: "Tirumala Hills InSAR line-of-sight displacement"
    }}
);

var tirumalaInsarLegend = L.control({{position: "bottomleft"}});
tirumalaInsarLegend.onAdd = function(map) {{
    var div = L.DomUtil.create("div", "info legend");
    div.style.background = "white";
    div.style.padding = "8px 10px";
    div.style.border = "1px solid #888";
    div.style.borderRadius = "4px";
    div.style.lineHeight = "1.5";
    div.innerHTML =
        "<b>InSAR LOS displacement</b><br>" +
        "Display range: -39.70 to -10.54 mm<br>" +
        "<span style='color:#0000ff'>Blue</span> to " +
        "<span style='color:#ff0000'>Red</span><br>" +
        "<small>Not a landslide probability map</small>";
    return div;
}};
tirumalaInsarLegend.addTo({map_variable});

"""

html = html[:control_index] + overlay_code + html[control_index:]

# Register the overlay in the existing layer-control object.
overlays_marker = "overlays :  {"
overlays_index = html.find(overlays_marker)

if overlays_index < 0:
    raise RuntimeError("Could not find the existing overlays dictionary.")

insert_at = overlays_index + len(overlays_marker)

html = (
    html[:insert_at]
    + '\n                    "InSAR LOS Displacement (80 m)": tirumalaInsarOverlay,'
    + html[insert_at:]
)

HTML_FILE.write_text(html, encoding="utf-8")

print("InSAR overlay added successfully.")
print("Updated HTML:", HTML_FILE)
print("Overlay PNG:", OVERLAY_FILE)
print("Map variable:", map_variable)
print("Overlay is available from the existing layer-control checkbox.")
